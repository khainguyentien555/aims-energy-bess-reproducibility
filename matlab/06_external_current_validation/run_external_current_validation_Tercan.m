function m = eval_alloc_current( ...
    x, ...
    ev, ...
    lambda, ...
    busData0, ...
    branchData, ...
    cfg, ...
    Imax_A, ...
    Ibase_A)

    bessMW = ...
        zeros(size(busData0,1),1);

    bessMW(ev) = ...
        x(:);

    bd = build_case_loads( ...
        busData0, ...
        ev, ...
        cfg.Pinst_MW, ...
        lambda, ...
        cfg.qFactorEVCS, ...
        bessMW, ...
        false);

    [V,Ibr,~,info] = ...
        bfs_power_flow( ...
        bd, ...
        branchData, ...
        cfg);

    m = current_metric( ...
        V, ...
        Ibr, ...
        branchData, ...
        Imax_A, ...
        Ibase_A, ...
        info);

end

function m = current_metric( ...
    V, ...
    Ibr, ...
    branchData, ...
    Imax_A, ...
    Ibase_A, ...
    info)

    IA = ...
        abs(Ibr(:))*Ibase_A;

    ratio = ...
        IA./Imax_A(:);

    [Rmax,idx] = ...
        max(ratio);

    m.converged = ...
        info.converged;

    m.BFSresidual = ...
        info.residual;

    m.Vmin = ...
        min(abs(V));

    m.I_A = ...
        IA;

    m.ratio = ...
        ratio;

    m.Rmax = ...
        Rmax;

    m.critIdx = ...
        idx;

    m.critFrom = ...
        branchData(idx,1);

    m.critTo = ...
        branchData(idx,2);

    m.Icrit_A = ...
        IA(idx);

    m.Ilimit_A = ...
        Imax_A(idx);

end

function OUT = solve_minimax_current( ...
    ev, ...
    lambda, ...
    busData0, ...
    branchData, ...
    cfg, ...
    Imax_A, ...
    Ibase_A)

    nE = ...
        numel(ev);

    Pev = ...
        cfg.Pinst_MW*lambda;

    lbx = ...
        zeros(nE,1);

    ubx = ...
        Pev*ones(nE,1);

    nStarts = ...
        cfg.nStarts;

    opts = optimoptions( ...
        'fmincon', ...
        'Algorithm','sqp', ...
        'Display','off', ...
        'SpecifyObjectiveGradient',true, ...
        'ConstraintTolerance',cfg.fminconConstrTol, ...
        'OptimalityTolerance',cfg.fminconOptTol, ...
        'StepTolerance',cfg.fminconStepTol, ...
        'MaxFunctionEvaluations',5000, ...
        'MaxIterations',1000);

    bestR = Inf;

    xbest = ...
        nan(nE,1);

    mbest = [];

    allR = ...
        nan(nStarts,1);

    allX = ...
        nan(nStarts,nE);

    for s = 1:nStarts

        if s == 1

            x0 = ubx;

        elseif s == 2

            x0 = 0.5*ubx;

        else

            x0 = ...
                ubx.*rand(nE,1);

        end

        m0 = eval_alloc_current( ...
            x0, ...
            ev, ...
            lambda, ...
            busData0, ...
            branchData, ...
            cfg, ...
            Imax_A, ...
            Ibase_A);

        gamma0 = ...
            m0.Rmax + 0.05;

        y0 = ...
            [x0; gamma0];

        lb = ...
            [lbx; 0];

        ub = ...
            [ubx; 10];

        [y,~,ef] = fmincon( ...
            @minimax_objective, ...
            y0, ...
            [],[],[],[], ...
            lb, ...
            ub, ...
            @(y) minimax_constraint( ...
                y, ...
                ev, ...
                lambda, ...
                busData0, ...
                branchData, ...
                cfg, ...
                Imax_A, ...
                Ibase_A), ...
            opts);

        x = ...
            y(1:nE);

        m = eval_alloc_current( ...
            x, ...
            ev, ...
            lambda, ...
            busData0, ...
            branchData, ...
            cfg, ...
            Imax_A, ...
            Ibase_A);

        if ef > 0 && m.converged

            allR(s) = ...
                m.Rmax;

            allX(s,:) = ...
                x(:).';

            if m.Rmax < bestR

                bestR = ...
                    m.Rmax;

                xbest = ...
                    x;

                mbest = ...
                    m;

            end

        end

    end

    valid = ...
        ~isnan(allR);

    if ~any(valid)

        error( ...
            'No successful minimax-current solution was obtained.');

    end

    OUT.Rmax = ...
        bestR;

    OUT.xbest = ...
        xbest;

    OUT.metric = ...
        mbest;

    OUT.nValidStarts = ...
        sum(valid);

    OUT.Rspread = ...
        max(allR(valid)) - min(allR(valid));

    OUT.allR = ...
        allR;

    OUT.allX = ...
        allX;

end

function [f,g] = minimax_objective(y)

    f = ...
        y(end);

    if nargout > 1

        g = ...
            zeros(numel(y),1);

        g(end) = ...
            1;

    end

end

function [c,ceq] = minimax_constraint( ...
    y, ...
    ev, ...
    lambda, ...
    busData0, ...
    branchData, ...
    cfg, ...
    Imax_A, ...
    Ibase_A)

    x = ...
        y(1:end-1);

    gamma = ...
        y(end);

    m = eval_alloc_current( ...
        x, ...
        ev, ...
        lambda, ...
        busData0, ...
        branchData, ...
        cfg, ...
        Imax_A, ...
        Ibase_A);

    c = ...
        m.ratio(:) - gamma;

    if ~m.converged

        c(:) = ...
            max(c(:),1);

    end

    ceq = [];

end

function OUT = solve_minimum_bess_current( ...
    xminimax, ...
    ev, ...
    lambda, ...
    busData0, ...
    branchData, ...
    cfg, ...
    Imax_A, ...
    Ibase_A, ...
    tauI)

    nE = ...
        numel(ev);

    Pev = ...
        cfg.Pinst_MW*lambda;

    lb = ...
        zeros(nE,1);

    ub = ...
        Pev*ones(nE,1);

    nStarts = ...
        cfg.nStarts;

    opts = optimoptions( ...
        'fmincon', ...
        'Algorithm','sqp', ...
        'Display','off', ...
        'SpecifyObjectiveGradient',true, ...
        'ConstraintTolerance',cfg.fminconConstrTol, ...
        'OptimalityTolerance',cfg.fminconOptTol, ...
        'StepTolerance',cfg.fminconStepTol, ...
        'MaxFunctionEvaluations',5000, ...
        'MaxIterations',1000);

    objs = ...
        nan(nStarts,1);

    allX = ...
        nan(nStarts,nE);

    bestObj = Inf;

    xbest = ...
        nan(nE,1);

    mbest = [];

    for s = 1:nStarts

        if s == 1

            x0 = ...
                xminimax;

        elseif s == 2

            x0 = ...
                ub;

        elseif s == 3

            x0 = ...
                0.5*(xminimax + ub);

        else

            x0 = ...
                ub.*rand(nE,1);

        end

        [x,~,ef] = fmincon( ...
            @sum_objective, ...
            x0, ...
            [],[],[],[], ...
            lb, ...
            ub, ...
            @(x) current_constraint( ...
                x, ...
                ev, ...
                lambda, ...
                busData0, ...
                branchData, ...
                cfg, ...
                Imax_A, ...
                Ibase_A), ...
            opts);

        m = eval_alloc_current( ...
            x, ...
            ev, ...
            lambda, ...
            busData0, ...
            branchData, ...
            cfg, ...
            Imax_A, ...
            Ibase_A);

        if ef > 0 && ...
                m.converged && ...
                m.Rmax <= 1 + tauI

            obj = ...
                sum(x);

            objs(s) = ...
                obj;

            allX(s,:) = ...
                x(:).';

            if obj < bestObj

                bestObj = ...
                    obj;

                xbest = ...
                    x;

                mbest = ...
                    m;

            end

        end

    end

    valid = ...
        ~isnan(objs);

    if ~any(valid)

        error( ...
            ['Minimax indicated current feasibility but minimum-BESS ' ...
             'optimization produced no accepted solution.']);

    end

    OUT.xbest = ...
        xbest;

    OUT.metric = ...
        mbest;

    OUT.nValidStarts = ...
        sum(valid);

    OUT.objSpread_kW = ...
        (max(objs(valid)) - min(objs(valid)))*1000;

    OUT.allObjectives_MW = ...
        objs;

    OUT.allX = ...
        allX;

end

