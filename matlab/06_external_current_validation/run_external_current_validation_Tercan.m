    end

end

function [c,ceq] = current_constraint( ...
    x, ...
    ev, ...
    lambda, ...
    busData0, ...
    branchData, ...
    cfg, ...
    Imax_A, ...
    Ibase_A)

    m = eval_alloc_current( ...
        x, ...
        ev, ...
        lambda, ...
        busData0, ...
        branchData, ...
        cfg, ...
        Imax_A, ...
        Ibase_A);

    c = ...
        m.ratio(:) - 1;

    if ~m.converged

        c(:) = ...
            max(c(:),1);

    end

    ceq = [];

end